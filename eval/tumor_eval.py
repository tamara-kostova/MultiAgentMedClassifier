# Directory names that are never class folders (annotations, predictions, etc.)
_DEFAULT_EXCLUDE_DIRS: frozenset[str] = frozenset({
    "pred", "Br35H-Mask-RCNN", "annotations", "__pycache__", ".DS_Store",
    "External_Test", "OVERLAY", "DICOM", "MASKS",
})


def load_dataset(
    data_dir: str,
    task: str,
    exclude_dirs: set[str] | None = None,
) -> list[dict]:
    """Scan <data_dir>/<class>/**/<image.*> (case-insensitive extensions).

    Automatically skips directories whose names end with '_mask' or appear
    in exclude_dirs (defaults to _DEFAULT_EXCLUDE_DIRS), at any nesting level
    under the class folder — e.g. a sibling `OVERLAY/` (annotated duplicates
    of `PNG/`) or `DICOM/` folder inside a class dir is skipped, not just
    excluded top-level class names.
    """
    excluded = _DEFAULT_EXCLUDE_DIRS | (exclude_dirs or set())
    root = Path(data_dir)
    samples = []
    for class_dir in sorted(root.iterdir()):
        if not class_dir.is_dir():
            continue
        if class_dir.name.endswith("_mask") or class_dir.name in excluded:
            continue
        for img_file in sorted(class_dir.rglob("*")):
            if img_file.suffix.lower() not in IMAGE_EXTENSIONS:
                continue
            if excluded.intersection(img_file.relative_to(class_dir).parts[:-1]):
                continue
            samples.append(
                {
                    "image_path": str(img_file),
                    "label": class_dir.name,
                    "task": task,
                }
            )
    return samples


def _interleave_by_label(samples: list[dict]) -> list[dict]:
    """Return samples in round-robin class order so caps stay class-balanced."""
    by_label: dict[str, list[dict]] = {}
    for sample in samples:
        by_label.setdefault(sample["label"], []).append(sample)

    labels = sorted(by_label)
    interleaved = []
    while any(by_label.values()):
        for label in labels:
            if by_label[label]:
                interleaved.append(by_label[label].pop(0))
    return interleaved


def _class_counts(samples: list[dict]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for sample in samples:
        counts[sample["label"]] = counts.get(sample["label"], 0) + 1
    return counts


_TUMOR_SUBTYPES = (
    "carcinoma",
    "germinoma",
    "glioma",
    "granuloma",
    "medulloblastoma",
    "meningioma",
    "neurocytoma",
    "papilloma",
    "schwannoma",
    "tuberculoma",
)


def canonical_label(value: object, task: str | None = None) -> str:
    """Normalize labels/predictions so metrics survive wording differences.

    The prompt schema uses the literal string "null" as the sentinel for an
    indeterminable field, so it must normalize to "" (absent) rather than being
    treated as a class name. Kept in sync with eval_analysis.canonical_label.
    """
    text = str(value or "").strip().lower()
    if not text or text in ("none", "null", "nan"):
        return ""

    normalized = (
        text.replace("_", " ")
        .replace("-", " ")
        .replace("/", " ")
        .replace("tumour", "tumor")
    )

    # "abnormal" / "other abnormalities" contains the substring "normal", so it must
    # be caught first — otherwise an abnormality assertion scores as a normal read.
    # The debate judge's schema offers "other abnormalities" as a verdict.
    if "abnormal" in normalized:
        return "abnormal"
    if "normal" in normalized or "control" in normalized:
        return "normal"
    if (
        normalized == "ms"
        or normalized.startswith("ms ")
        or " multiple sclerosis" in f" {normalized}"
    ):
        return "ms"
    if any(
        token in normalized
        for token in ("stroke", "ischemic", "ischemia", "hemorrhagic", "bleeding", "infarct")
    ):
        return "stroke"

    tumor_subtype = next(
        (subtype for subtype in _TUMOR_SUBTYPES if subtype in normalized),
        None,
    )
    tumorish = (
        tumor_subtype is not None
        or "pituitary" in normalized
        or "brain tumor" in normalized
        or normalized == "tumor"
        or " tumor" in normalized
    )
    if task == "binary_tumor" and tumorish:
        return "tumor"
    if "pituitary" in normalized:
        return "pituitary_tumor"
    if tumor_subtype is not None:
        return tumor_subtype
    if tumorish:
        return "tumor"

    return text


def load_processed_paths(jsonl_path: Path) -> set[str]:
    """Return image_path values that are already written in the JSONL file."""
    if not jsonl_path.exists():
        return set()
    done: set[str] = set()
    with jsonl_path.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
                if rec.get("image_path") and rec.get("error") is None:
                    done.add(rec["image_path"])
            except json.JSONDecodeError:
                pass
    return done


def extract_row(
    sample: dict,
    final_state: NeuroimagingState,
    latency: float,
    label_map: dict[str, str] | None = None,
    error: str | None = None,
) -> dict:
    """Build the rich JSONL record from a completed pipeline state."""
    seg = final_state.get("segmentation_result") or {}
    cnn = final_state.get("classification_result") or {}
    clip = final_state.get("biomedclip_result") or {}
    expl = final_state.get("explainability_result") or {}
    verif = final_state.get("verification_result") or {}
    fhir = final_state.get("fhir_report") or {}

    raw_label = sample["label"]
    label_name = (label_map or {}).get(raw_label, raw_label)
    predicted_class = final_state.get("final_predicted_class")
    cnn_predicted_class = cnn.get("predicted_class")

    return {
        # ── Identity ──────────────────────────────────────────────────────────
        "image_path": sample["image_path"],
        "true_label": raw_label,
        "true_label_name": label_name,
        "true_label_canonical": canonical_label(label_name, sample["task"]),
        "task": sample["task"],
        "timestamp": datetime.now(timezone.utc).isoformat(),
        # ── Final prediction ──────────────────────────────────────────────────
        "predicted_class": predicted_class,
        "predicted_class_canonical": canonical_label(predicted_class, sample["task"]),
        "final_confidence": final_state.get("final_confidence", 0.0),
        "requires_human_review": final_state.get("requires_human_review", False),
        # ── Routing ───────────────────────────────────────────────────────────
        "routing_path": " → ".join(final_state.get("routing_path", [])),
        "routing_decision": final_state.get("routing_decision"),
        "routing_confidence": final_state.get("routing_confidence", 0.0),
        "routing_reasoning": final_state.get("routing_reasoning", ""),
        "suspected_pathology": final_state.get("suspected_pathology", ""),
        # ── MedGemma structured diagnoses ─────────────────────────────────────
        "medgemma_diagnosis": final_state.get("medgemma_diagnosis"),
        "medgemma_bbox_diagnosis": final_state.get("medgemma_bbox_diagnosis"),
        "final_medgemma_diagnosis": final_state.get("final_medgemma_diagnosis"),
        # ── CNN ───────────────────────────────────────────────────────────────
        "cnn_predicted_class": cnn_predicted_class,
        "cnn_predicted_class_canonical": canonical_label(
            cnn_predicted_class, sample["task"]
        ),
        "cnn_confidence": cnn.get("confidence"),
        "cnn_all_probs": cnn.get("all_probs"),
        # ── SAM3 ──────────────────────────────────────────────────────────────
        "sam3_mask_path": seg.get("mask_path"),
        "sam3_bbox": seg.get("bbox"),
        "sam3_guided_image_path": seg.get("guided_image_path"),

        "sam3_skipped": seg.get("skipped", False),
        "sam3_mask_empty": final_state.get("sam3_mask_empty", False),
        # ── BiomedCLIP ────────────────────────────────────────────────────────
        "biomedclip_top_label": clip.get("top_label"),
        "biomedclip_top_score": clip.get("top_score"),
        "biomedclip_ranked_labels": clip.get("ranked_labels"),
        "biomedclip_scores": clip.get("scores"),
        "biomedclip_mode": clip.get("mode"),
        # ── Explainability ────────────────────────────────────────────────────
        "gradcam_pp_path": expl.get("gradcam_pp"),
        "integrated_gradients_path": expl.get("integrated_gradients"),
        "saliency_sam3_iou": final_state.get("saliency_sam3_iou"),
        # ── Verification (MedGemma vs CNN) ────────────────────────────────────
        "verification_agreement": verif.get("agreement"),
        "verification_alternative_dx": verif.get("alternative_diagnosis"),
        "verification_reasoning": verif.get("reasoning"),
        # ── Agent Forest (System C) — None outside --pipeline_mode forest ─────
        "dissent_rate": (final_state.get("forest_consensus") or {}).get("dissent_rate"),
        "vote_fraction": (final_state.get("forest_consensus") or {}).get("vote_fraction"),
        "forest_votes": final_state.get("forest_votes"),
        # ── Multi-Agent Debate (System B) — None outside --pipeline_mode debate ─
        "debate_rounds_completed": final_state.get("debate_rounds_completed"),
        "debate_round_changed": (final_state.get("debate_verdict") or {}).get("round_changed"),
        "debate_winner": (final_state.get("debate_verdict") or {}).get("winner"),
        # ── Full MedGemma report ──────────────────────────────────────────────
        "final_report": final_state.get("final_report"),
        # ── FHIR ──────────────────────────────────────────────────────────────
        "fhir_bundle_id": fhir.get("id"),
        # ── Perf / error ──────────────────────────────────────────────────────
        "latency_s": latency,
        "error": error,
    }


def _print_progress(i: int, total: int, row: dict, elapsed: float) -> None:
    eta_s = (elapsed / i) * (total - i) if i > 0 else 0.0
    pred = row.get("predicted_class") or row.get("error") or "?"
    pred_short = (pred[:28] + "…") if len(str(pred)) > 29 else pred
    print(
        f"  [{i:>4}/{total}] {Path(row['image_path']).name:<28} "
        f"true={row.get('true_label_name', row.get('true_label', '?')):<12} "
        f"pred={pred_short:<29} "
        f"conf={row.get('final_confidence', 0.0):.3f}  "
        f"lat={row['latency_s']:.1f}s  ETA={eta_s/60:.0f}min"
    )


def print_summary(rows: list[dict]) -> None:
    ok = [r for r in rows if r.get("error") is None]
    err = [r for r in rows if r.get("error") is not None]

    print(f"\n{'='*60}")
    print(f"Evaluation complete — {len(ok)} succeeded, {len(err)} errors")

    if not ok:
        if err:
            print(f"  First error: {err[0]['error']}")
        return

    y_true = [
        r.get("true_label_canonical")
        or canonical_label(r.get("true_label_name") or r["true_label"], r.get("task"))
        for r in ok
    ]
    y_pred = [
        r.get("predicted_class_canonical")
        or canonical_label(r.get("predicted_class"), r.get("task"))
        for r in ok
    ]
    y_cnn = [
        r.get("cnn_predicted_class_canonical")
        or canonical_label(r.get("cnn_predicted_class"), r.get("task"))
        for r in ok
    ]

    acc = accuracy_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred, average="macro", zero_division=0)
    cnn_acc = accuracy_score(y_true, y_cnn)

    sam3_rate = sum(1 for r in ok if r.get("sam3_mask_path")) / len(ok)
    clip_rate = sum(1 for r in ok if r.get("biomedclip_top_label")) / len(ok)
    expl_rate = sum(1 for r in ok if r.get("gradcam_pp_path")) / len(ok)
    iou_vals = [
        r["saliency_sam3_iou"]
        for r in ok
        if r.get("saliency_sam3_iou") is not None
    ]
    review_rate = sum(1 for r in ok if r.get("requires_human_review")) / len(ok)
    mean_lat = sum(r["latency_s"] for r in ok) / len(ok)

    print(f"  Final accuracy (MedGemma fused): {acc:.4f}")
    print(f"  CNN-only accuracy:               {cnn_acc:.4f}")
    print(f"  F1 macro (fused):                {f1:.4f}")
    print(f"  SAM3 ran:                        {sam3_rate:.1%}  ({sum(1 for r in ok if r.get('sam3_mask_path'))}/{len(ok)})")
    print(f"  BiomedCLIP ran:                  {clip_rate:.1%}")
    print(f"  Explainability ran:              {expl_rate:.1%}")
    if iou_vals:
        print(f"  Mean GradCAM/SAM3 IoU:          {sum(iou_vals)/len(iou_vals):.3f}  (n={len(iou_vals)})")
    print(f"  Human review flagged:            {review_rate:.1%}")
    print(f"  Mean latency:                    {mean_lat:.1f}s/image")
    if err:
        print(f"  Errors:                          {len(err)}")
    print(f"{'='*60}")


def run_tumor_eval(
    app,
    data_dir: str,
    task: str,
    output_file: Path,
    label_map: dict[str, str] | None = None,
    max_samples: int | None = None,
    exclude_dirs: set[str] | None = None,
) -> list[dict]:
    """
    Run the full pipeline on every image in data_dir, writing results to output_file.

    Returns the list of row dicts produced in this run (does not include rows from
    a prior resumed run).

    max_samples caps the total number of images processed across all runs combined.
    label_map=None uses the task default; label_map={} uses raw folder names.
    """
    if label_map is None:
        label_map = LABEL_MAPS.get(TASK_DEFAULT_LABEL_MAP.get(task, ""), {})

    output_file = Path(output_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)

    samples = _interleave_by_label(load_dataset(data_dir, task, exclude_dirs=exclude_dirs))
    if not samples:
        print(f"No images found in {data_dir}")
        return []
    print(
        f"Dataset: {len(samples)} images  task={task}  dir={data_dir}  "
        f"classes={_class_counts(samples)}"
    )

    done = load_processed_paths(output_file)
    pending = [s for s in samples if s["image_path"] not in done]

    if max_samples is not None:
        already_done = len(done)
        remaining_budget = max(0, max_samples - already_done)
        pending = pending[:remaining_budget]

    if done:
        cap_note = f"  (capped at {max_samples} total)" if max_samples is not None else ""
        print(f"Resuming — {len(done)} already done, {len(pending)} remaining{cap_note}")
    else:
        cap_note = f"  (capped at {max_samples})" if max_samples is not None else ""
        print(f"Starting fresh — {len(pending)} images to process{cap_note}")

    if not pending:
        print("Nothing to do.")
        return []
    print(f"Pending class mix: {_class_counts(pending)}")

    rows_this_run: list[dict] = []
    t_start = time.perf_counter()

    with output_file.open("a", encoding="utf-8") as f:
        for i, sample in enumerate(pending, start=1):
            t0 = time.perf_counter()
            try:
                state = initial_state(sample["image_path"], sample["task"])
                final_state: NeuroimagingState = app.invoke(state)
                latency = time.perf_counter() - t0
                row = extract_row(sample, final_state, latency, label_map)
            except Exception as exc:
                latency = time.perf_counter() - t0
                empty = initial_state(sample["image_path"], sample["task"])
                row = extract_row(sample, empty, latency, label_map, error=str(exc))
                print(f"\n  [ERROR] {Path(sample['image_path']).name}: {exc}")

            f.write(json.dumps(row) + "\n")
            f.flush()
            rows_this_run.append(row)
            _print_progress(i, len(pending), row, time.perf_counter() - t_start)

    print_summary(rows_this_run)
    print(f"\nResults written to: {output_file}")
    return rows_this_run


run_dataset_eval = run_tumor_eval
